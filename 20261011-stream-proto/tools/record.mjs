// 录对比视频：CDP 截屏流（2x DPR），按真实时间戳拼成 30fps H.264。用法：node tools/record.mjs [serif]
import { createRequire } from "module";
import fs from "fs";
import { execFileSync } from "child_process";
const require = createRequire("/workspace/By-Your-Side/package.json");
const { chromium } = require("playwright");
const serif = process.argv[2] === "serif";
const out = serif ? "compare-serif.mp4" : "compare.mp4";
const dir = `/tmp/rec-stream-${serif ? "serif" : "sans"}`; fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir);
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const W = 824, H = 904;
const ctx = await browser.newContext({ deviceScaleFactor: 2, viewport: { width: W, height: H } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.error("PAGEERR", e.message));
await page.goto(`file:///workspace/bys-stream-proto/index.html?rec=1${serif ? "&serif=1" : ""}`);
await page.waitForTimeout(1000);
console.log("main height", await page.evaluate(() => document.querySelector("main").getBoundingClientRect().height));
const cdp = await ctx.newCDPSession(page);
const frames = [];
cdp.on("Page.screencastFrame", async (f) => {
  const file = `${dir}/f${String(frames.length).padStart(5, "0")}.jpg`;
  fs.writeFileSync(file, Buffer.from(f.data, "base64"));
  frames.push({ file, ts: f.metadata.timestamp });
  cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }).catch(() => {});
});
await page.addStyleTag({ content: "body::after{content:'';position:fixed;right:0;bottom:0;width:1px;height:1px;animation:tick 1s linear infinite}@keyframes tick{to{opacity:.99}}" });
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, everyNthFrame: 1, maxWidth: W * 2, maxHeight: H * 2 });
await page.waitForTimeout(400);
await page.evaluate(() => window.__start());
await page.waitForFunction(() => window.__recDone === true, null, { timeout: 60000, polling: 100 });
await page.waitForTimeout(300);
await cdp.send("Page.stopScreencast");
await browser.close();
const end = frames[frames.length - 1].ts + 0.04;
let list = "";
frames.forEach((f, i) => { const d = (i + 1 < frames.length ? frames[i + 1].ts : end) - f.ts; list += `file '${f.file}'\nduration ${Math.max(0.001, d).toFixed(4)}\n`; });
list += `file '${frames[frames.length - 1].file}'\n`;
fs.writeFileSync(`${dir}/list.txt`, list);
execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", `${dir}/list.txt`, "-vf", `fps=30,scale=${W * 2}:-2:flags=lanczos,format=yuv420p`, "-c:v", "libx264", "-preset", "slow", "-crf", "17", "-movflags", "+faststart", out]);
console.log(out, frames.length, "frames", (end - frames[0].ts).toFixed(1), "s");
